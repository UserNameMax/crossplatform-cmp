package band.effective.education.crossplatform.platform

/**
 * То, что общий код узнать о себе не может, — и потому спрашивает у таргета.
 *
 * Каждое поле выбрано так, чтобы **ответы разных таргетов расходились** и это
 * было видно с экрана: одно и то же демо, запущенное на desktop и в браузере,
 * показывает разные строки. В этом весь смысл `expect`.
 */
interface PlatformFacts {
    /** Как таргет называет себя сам. */
    val targetName: String

    /** Куда этот таргет кладёт ключ→строка и как это называется у него. */
    val storageKind: String

    /** Есть ли у страницы адрес, который видит пользователь. */
    val hasPageAddress: Boolean

    /** Что стало с `expect`-функцией при сборке: имя механизма подстановки. */
    val bindingKind: String

    /**
     * Живой дамп: то, что таргет может рассказать о себе **в рантайме**, а не
     * то, что мы про него написали. Инструмент, описывающий сам себя, —
     * первый в порядке доверия к источникам.
     */
    fun selfReport(): List<String>
}

expect fun platformFacts(): PlatformFacts
