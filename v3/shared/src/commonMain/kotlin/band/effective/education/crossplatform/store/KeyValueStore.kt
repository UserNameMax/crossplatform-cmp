package band.effective.education.crossplatform.store

/**
 * Самое маленькое хранилище, которое переживает закрытие приложения.
 *
 * Ключ → строка, и ничего больше. Всё остальное — списки, множества, записи
 * каталога — складывается в строку сериализацией поверх этого интерфейса.
 *
 * **Почему не библиотека.** Мы смотрели на готовые: `androidx.datastore` версии
 * 1.2.0 публикует вариант под `wasmJs`, но не под `js`, и в `commonMain` проекта
 * с обоими web-таргетами он просто не резолвится (проверено 25.08.2026). А то,
 * что резолвится, ещё не значит, что работает: у `DataStoreFactory` в wasm-варианте
 * тело — `TODO("Not yet implemented")`.
 *
 * Отсюда правило вехи: **библиотеку хранилища проверяют прогоном на web до того,
 * как на неё сядут**, а не после.
 */
interface KeyValueStore {
    fun getString(key: String): String?
    fun putString(key: String, value: String)
    fun remove(key: String)
}

/**
 * Тот самый `expect`, ради которого существует эта веха.
 *
 * Это не мост и не вызов через прослойку: компилятор подставляет реализацию
 * своего таргета **на этапе компиляции**. Если для какого-то таргета `actual`
 * не написан, ломается сборка, а не приложение у пользователя.
 */
expect fun createKeyValueStore(): KeyValueStore

/** Имя хранилища одно на все таргеты — меняются только способ и место записи. */
internal const val STORE_NAME = "lection5-stand"
